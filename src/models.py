"""
Pydantic data models for AdVantage-Edge Contextual Intent Arbiter.
Strict typing and JSON schema validation conforming to YouTube Shoppable Card and RCS specifications.
"""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class EvaluationMode(str, Enum):
    """Execution mode for contextual ingestion."""
    SEARCH = "SEARCH"
    YOUTUBE_STREAM = "YOUTUBE_STREAM"


class InputContext(BaseModel):
    """
    Ingested user request context.
    Mode A: Multi-turn conversational search query.
    Mode B: YouTube video transcript stream with metadata.
    """
    text: str = Field(..., description="Conversational user text or transcript chunk text")
    timestamp: Optional[float] = Field(default=None, description="Video timestamp in seconds (for YouTube mode)")
    channel_category: Optional[str] = Field(default=None, description="YouTube channel vertical / topic category")
    session_history: Optional[List[str]] = Field(default_factory=list, description="Prior conversational turns or search queries")


class IntentAnalysis(BaseModel):
    """
    Dual-head probabilistic classification generated by local LLM.
    """
    commercial_intent_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Continuous score indicating purchasing or transaction intent (0.0 - 1.0)"
    )
    intent_category: str = Field(
        ...,
        description="Classified domain category (e.g., DIY/repair, product_review, medical_emergency, casual_entertainment)"
    )
    intrusiveness_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Narrative disruption or user fatigue risk score (0.0 - 1.0)"
    )


class PolicyDecision(BaseModel):
    """
    Deterministic safety policy verdict.
    """
    allow_monetization: bool = Field(..., description="Whether commercial ad placement is cleared")
    suppression_reason: Optional[str] = Field(None, description="Detailed policy justification if monetization is suppressed")
    sensitive_flags: List[str] = Field(default_factory=list, description="Detected safety flags (e.g., medical_crisis, tragedy)")


class AdCandidate(BaseModel):
    """
    Commercial listing record retrieved from catalog database.
    """
    product_id: str = Field(..., description="Unique SKU identifier")
    title: str = Field(..., description="Product title")
    category: str = Field(..., description="Product vertical/category")
    bid: float = Field(..., ge=0.0, description="Advertiser max bid in USD (eCPM driver)")
    ctr: float = Field(..., ge=0.0, le=1.0, description="Historical Click-Through Rate")
    price: float = Field(..., ge=0.0, description="Retail selling price")
    merchant: str = Field(..., description="Verified merchant name")
    deep_link: str = Field(..., description="Target landing URL or deep link")
    ranking_score: Optional[float] = Field(default=0.0, description="Calculated expected value score")


class RichCardPayload(BaseModel):
    """
    Google Shoppable Rich Card / RCS Business Messaging compliant JSON payload.
    """
    headline: str = Field(..., description="Shoppable card display title")
    merchant_name: str = Field(..., description="Brand or merchant label")
    price_display: str = Field(..., description="Formatted price string, e.g., '$149.99'")
    call_to_action_url: str = Field(..., description="Shoppable deep link URL")
    attribution_label: str = Field(default="Sponsored", description="Google Ads compliance attribution label")
    explanation: str = Field(..., description="Contextual ad placement rationale for user transparency")


class ArbiterOutput(BaseModel):
    """
    Final end-to-end response payload containing organic context, decision, optional sponsored card, and latency.
    """
    mode: EvaluationMode = Field(..., description="Ingestion mode used")
    organic_response: str = Field(..., description="AI Overview organic answer or video narrative bridge")
    decision: PolicyDecision = Field(..., description="Deterministic monetization decision")
    sponsored_card: Optional[RichCardPayload] = Field(None, description="Synthesized shoppable ad payload if monetization cleared")
    latency_ms: float = Field(..., ge=0.0, description="End-to-end evaluation latency in milliseconds")
